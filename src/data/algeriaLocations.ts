export function getWilayaByCode(codeOrName: string): WilayaInfo {
  if (!codeOrName) return ALGERIA_WILAYAS[15]; // Default Alger (16)

  const clean = String(codeOrName).trim();
  const numericCode = clean.replace(/^0+/, '');

  const found = ALGERIA_WILAYAS.find((w) => {
    const wNumeric = w.code.replace(/^0+/, '');
    return (
      w.code === clean ||
      wNumeric === numericCode ||
      w.nameAr.includes(clean) ||
      w.nameFr.toLowerCase().includes(clean.toLowerCase())
    );
  });

  return found || ALGERIA_WILAYAS[15]; // Fallback to Alger (16)
}
